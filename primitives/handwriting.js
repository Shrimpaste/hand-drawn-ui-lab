const cache = new Map();
export function handwrittenPaths(text, seed = 1) {
  const key = text + "|" + seed;
  if (cache.has(key)) return cache.get(key);
  const r = random(seed);
  let x = 0;
  const paths = [];
  for (const ch of text.toLowerCase()) {
    if (ch === " ") {
      x += 0.4 + r() * 0.06;
      continue;
    }
    const g = glyphs[ch] || glyphs["?"],
      tilt = (r() - 0.5) * 0.16,
      sy = 0.92 + r() * 0.14,
      base = (r() - 0.5) * 0.065;
    let max = 0;
    for (const knots of g) {
      const raw = curvePoints(knots, { steps: 8 });
      const p = raw.map(([a, b]) => {
        max = Math.max(max, a);
        return [x + a + tilt * (1 - b), b * sy + base];
      });
      paths.push(p);
    }
    x += max + 0.13 + (r() - 0.5) * 0.065;
  }
  const out = {
    paths,
    width: x,
    total: paths.reduce((s, p) => s + length(p), 0),
  };
  if (cache.size > 140) cache.delete(cache.keys().next().value);
  cache.set(key, out);
  return out;
}
export function handwriting(
  c,
  text,
  x,
  y,
  {
    size = 23,
    color = palette.ink,
    progress = 1,
    align = "left",
    seed = 31,
    width = 1.4,
    alpha = 1,
  } = {},
) {
  if (progress <= 0) return;
  const d = handwrittenPaths(text, seed);
  let remaining = d.total * Math.min(1, progress);
  c.save();
  c.translate(
    x -
      (align === "center"
        ? (d.width * size) / 2
        : align === "right"
          ? d.width * size
          : 0),
    y,
  );
  c.scale(size, size);
  c.globalAlpha *= alpha;
  for (let i = 0; i < d.paths.length && remaining > 0; i++) {
    const p = d.paths[i],
      len = length(p),
      shown = remaining < len ? partial(p, remaining) : p;
    penLine(c, shown, {
      seed: seed + i * 7,
      width: width / size,
      color,
      boil: 0.002,
    });
    remaining -= len;
  }
  c.restore();
  return d.width * size;
}
