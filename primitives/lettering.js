const cache = new Map();
export function textStrokes(text) {
  if (cache.has(text)) return cache.get(text);
  let offset = 0,
    paths = [];
  for (const char of text.toUpperCase()) {
    if (char === " ") {
      offset += 0.55;
      continue;
    }
    for (const path of glyphs[char] || glyphs["?"])
      paths.push(path.map(([x, y]) => [x + offset + y * 0.055, y]));
    offset += 0.96;
  }
  const total = paths.reduce((sum, p) => sum + length(p), 0),
    result = { paths, total, width: Math.max(0, offset - 0.18) };
  if (cache.size > 180) cache.delete(cache.keys().next().value);
  cache.set(text, result);
  return result;
}
export function penText(
  ctx,
  text,
  x,
  y,
  {
    size = 16,
    color = colors.ink,
    progress = 1,
    align = "left",
    alpha = 1,
    seed = 27,
    width = 1.25,
  } = {},
) {
  if (progress <= 0) return;
  const data = textStrokes(text);
  let budget = data.total * Math.min(1, progress),
    n = 0;
  ctx.save();
  ctx.translate(
    x -
      (align === "center"
        ? (data.width * size) / 2
        : align === "right"
          ? data.width * size
          : 0),
    y,
  );
  ctx.scale(size, size);
  for (const path of data.paths) {
    const span = length(path);
    stroke(ctx, path, {
      color,
      width: width / size,
      progress: Math.min(1, budget / span),
      seed: seed + n++,
      jitter: 0.017,
      alpha,
    });
    budget -= span;
    if (budget <= 0) break;
  }
  ctx.restore();
}
export function prose(
  ctx,
  text,
  x,
  y,
  {
    size = 16,
    color = colors.ink,
    align = "left",
    italic = false,
    alpha = 1,
  } = {},
) {
  ctx.save();
  ctx.globalAlpha *= alpha;
  ctx.fillStyle = color;
  ctx.font = `${italic ? "italic " : ""}${size}px ${italic ? "Georgia" : '"Segoe Print", "Comic Sans MS", cursive'}`;
  ctx.textAlign = align;
  ctx.fillText(text, x, y);
  ctx.restore();
}
