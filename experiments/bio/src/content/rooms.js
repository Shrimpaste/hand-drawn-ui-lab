/** Every string that is drawn as handwriting, for glyph coverage checks. */
export function handwrittenStrings() {
  const out = [];
  const walk = (v) => {
    if (typeof v === "string") out.push(v);
    else if (Array.isArray(v)) v.forEach(walk);
    else if (v && typeof v === "object") Object.values(v).forEach(walk);
  };
  for (const r of ROOMS) walk([r.door, r.no, r.title, r.hint]);
  walk([HALL.title, HALL.subtitle, HALL.greet, HALL.idle, HALL.vein, HALL.caseLabel, HALL.caseHint, HALL.close, HALL.triad]);
  walk([HALL.caseNote.kicker, HALL.caseNote.title, HALL.caseNote.key]);
  for (const steps of Object.values(STORY)) for (const s of steps) walk([s.say, s.note.kicker, s.note.title, s.note.key]);
  walk(LABELS);
  return out;
}
